//==============================================================================
//  文件名  : cfg_cdc.v
//  模块名  : cfg_cdc
//  功能    : 多比特配置数据的安全跨时钟域传输（toggle 握手方式）
//------------------------------------------------------------------------------
//  【为什么需要这个模块】
//  本作品里有 3 个时钟域：
//      clk         50MHz  —— 按键状态机 key_ctrl_fsm 在这里（配置参数的"产生地"）
//      sd_card_clk 100MHz —— 图片读取 sd_card_bmp 在这里（需要 period_sel）
//      video_clk   25MHz  —— 图像处理流水线在这里（需要亮度/对比度/模式等）
//
//  按键改变参数后，必须把这个值安全地"送过时钟域边界"。
//
//  【为什么不能直接连】
//  两个时钟是各走各的（异步的）。多比特信号直接跨域时，各个比特的
//  传播延迟不同，目的时钟域可能采到"一半新一半旧"的错误值
//  （例如 亮度从 15(01111) 变成 16(10000)，可能采到 31）。
//  这就是经典的"多比特跨时钟域"问题。
//
//  【本模块的解决办法 —— toggle 握手】
//    源域：数据一变，就把一个 1bit 的 toggle 信号翻转一次
//          （1bit 信号跨域是安全的：要么采到 0 要么采到 1，不会"半新半旧"）
//    目的域：把 toggle 打 3 拍同步，检测到它的边沿时，说明"源域的数据已经
//            稳定很久了"，这时才把数据锁存下来用。
//
//    时序关系（以源域 50MHz、目的域 25MHz 为例）：
//      源域第 N 拍   ：数据变化 + toggle 翻转
//      目的域 +1 拍  ：数据到达（可能还没稳定）
//      目的域 +2 拍  ：数据稳定（2 级同步器输出）→ S_data_s0
//      目的域 +3 拍  ：S_data_s1
//      目的域 +...   ：toggle 的第 3 级同步完成，检测到边沿
//      检测到边沿的这一刻，S_data_s1 已经是稳定的新数据 ✔
//
//  【使用前提（很重要）】
//    被传输的数据必须"变化很慢"，即变化间隔 ≫ 目的时钟的 3 个周期。
//    本工程里配置参数只在按键时才变，间隔至少 150ms，
//    而目的时钟周期只有 10~40ns，余量上万倍，绝对安全。
//
//    这个写法与工程中已有的 frame_write_toggle_mem（顶层）完全一致，
//    是安路工程里的惯用手法。
//------------------------------------------------------------------------------
//  所属工程: 基于安路 EG4S20 的智能数字广告牌系统（赛题一改造）
//  说明    : 详细中文注释版，供零基础队员阅读理解
//==============================================================================

module cfg_cdc #(
    parameter integer WIDTH = 16          // 要传输的数据位宽
)(
    // ---------------- 源时钟域 ----------------
    input  wire             I_clk_src,    // 源时钟
    input  wire             I_rst_src,    // 源域复位（高有效）
    input  wire [WIDTH-1:0] I_data,       // 源域数据（变化必须很慢！）

    // ---------------- 目的时钟域 ----------------
    input  wire             I_clk_dst,    // 目的时钟
    input  wire             I_rst_dst,    // 目的域复位（高有效）
    output reg  [WIDTH-1:0] O_data        // 目的域锁存到的稳定数据
);

    //==========================================================================
    //  源时钟域：数据寄存 + 变化时翻转 toggle
    //==========================================================================
    reg [WIDTH-1:0] S_data_r;             // 上一拍的数据，用于比较
    reg             S_toggle;             // 1bit 跨域握手信号

    always @(posedge I_clk_src or posedge I_rst_src) begin
        if (I_rst_src) begin
            S_data_r <= {WIDTH{1'b0}};
            S_toggle <= 1'b0;
        end else begin
            S_data_r <= I_data;
            if (I_data != S_data_r)       // 数据发生变化 → 翻转 toggle
                S_toggle <= ~S_toggle;
        end
    end

    //==========================================================================
    //  目的时钟域：同步 + 边沿检测 + 锁存
    //==========================================================================
    reg [WIDTH-1:0] S_data_s0;            // 数据 2 级同步
    reg [WIDTH-1:0] S_data_s1;
    reg [2:0]       S_tgl_sync;           // toggle 3 级同步

    always @(posedge I_clk_dst or posedge I_rst_dst) begin
        if (I_rst_dst) begin
            S_data_s0  <= {WIDTH{1'b0}};
            S_data_s1  <= {WIDTH{1'b0}};
            S_tgl_sync <= 3'b000;
            O_data     <= {WIDTH{1'b0}};
        end else begin
            // 数据打 2 拍（同步 + 等它稳定）
            S_data_s0 <= S_data_r;
            S_data_s1 <= S_data_s0;

            // toggle 打 3 拍
            S_tgl_sync <= {S_tgl_sync[1:0], S_toggle};

            // 检测 toggle 的任意边沿（上升或下降都算一次"数据已更新"）
            // 此时 S_data_s1 已经是稳定的新数据，可以放心锁存
            if (S_tgl_sync[2] ^ S_tgl_sync[1])
                O_data <= S_data_s1;
        end
    end

endmodule
