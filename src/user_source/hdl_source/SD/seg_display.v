//==============================================================================
//  文件名  : seg_display.v
//  模块名  : seg_display
//  功能    : 6 位数码管的显示内容合成
//------------------------------------------------------------------------------
//  【为什么要这个模块】
//  原例程只用数码管的最高位显示 bmp_read 的状态码，其余 5 位全灭。
//  改造后系统有了更多状态（运行/调节模式、当前参数、亮度值、周期…），
//  用一个模块统一组织显示内容，比在顶层里堆一堆 case 更清晰。
//
//  【显示版面（6 位，从 seg_data_5 到 seg_data_0）】
//
//   位   RUN 运行模式              ADJUST 调节模式
//   ---------------------------------------------------------------------
//    5   bmp_read 状态码            bmp_read 状态码
//        (1=空闲 2=扫描 3=等待 4=装载)  （与原例程保持一致，便于排查问题）
//   ---------------------------------------------------------------------
//    4   1 = 运行模式               2 = 调节模式
//   ---------------------------------------------------------------------
//    3   A = 自动轮播进行中         1/2/3/4 = 当前调节项
//        − = 自动轮播已关闭          1=亮度 2=对比度 3=轮播周期 4=缩放(×10)
//   ---------------------------------------------------------------------
//    2   数值十位                  数值十位
//    1   数值个位                  数值个位
//   ---------------------------------------------------------------------
//    0   −（横杠，作分隔符）        −（横杠，作分隔符）
//
//  【数值显示的是什么】
//    RUN  模式：当前轮播周期（秒），例如 05 表示 5 秒
//    ADJUST 模式：当前调节项的数值（亮度 00~31 / 对比度 00~31 / 周期秒数 /
//                 缩放百分比÷10：100% 显示 10、50% 显示 05、200% 显示 20）
//                 ★ 缩放是三位数(50~200)，两位数码管装不下，所以顶层已经
//                   先除以 10 再送进来，位 3 的 "4" 就是"读数 ×10"的提示。
//
//  【数码管电气特性（沿用工程原有约定）】
//    共阳数码管，段码低电平点亮：seg_data 的 bit[6:0] 为 7 段码，
//    bit[7] 是小数点（1 = 不亮）。整位熄灭时输出 8'hFF。
//    译码直接复用工程自带的 seg_decoder 模块（SD/seg_decoder.v）。
//------------------------------------------------------------------------------
//  所属工程: 基于安路 EG4S20 的智能数字广告牌系统（赛题一改造）
//  说明    : 详细中文注释版，供零基础队员阅读理解
//==============================================================================

module seg_display (
    // ---------------- 输入：要显示的信息 ----------------
    input  wire [3:0]  I_state_code,   // bmp_read 的状态码（沿用原例程功能）
    input  wire        I_adj_mode,     // 0 = RUN 运行模式，1 = ADJUST 调节模式
    input  wire [1:0]  I_adj_sel,      // 调节项 0=亮度 1=对比度 2=周期 3=缩放
    input  wire        I_auto_play,    // 自动轮播开关状态（1=正在自动轮播）
    input  wire [15:0] I_value,        // 要显示的数值（0..99）

    // ---------------- 字幕调试模式（SW3 打开时生效）----------------
    //  ★ 为什么要有这个？
    //    "字幕没出来"可能是两种完全不同的故障：
    //        ① 压根没从 TF 卡读到字（读取端问题）→ 查 TF 卡 / 文件标记 / 编码
    //        ② 读到了但没画出来（显示端问题）  → 查字库 / 流水线
    //    光看屏幕是分不出来的，所以在数码管上开个后门：
    //        SW3 拨到 ON → 数码管显示 [状态][错误码][百][十][个][横杠]
    //    正常应该是   4 0 0 3 4 -   （状态=4已完成，错误=0，收到 34 个字）
    //    什么都没有是 0 0 0 0 0 -   （状态=0 还在等，或扫描根本没启动）
    //    读不到文件是 5 1 0 0 0 -   （状态=5 出错，错误码=1 找不到文件）
    input  wire        I_debug,        // SW3：1 = 数码管改显示字幕调试信息
    input  wire [3:0]  I_txt_state,    // txt_read 状态码 0~5
    input  wire [2:0]  I_txt_err,      // txt_read 错误码 0~2
    input  wire [9:0]  I_txt_len,      // 已经收到的字幕字符数（★ 这里必须有逗号！）

    // ---------------- 输出：6 位数码管的段码 ----------------
    output wire [7:0]  O_seg_0,        // 最低位
    output wire [7:0]  O_seg_1,
    output wire [7:0]  O_seg_2,
    output wire [7:0]  O_seg_3,
    output wire [7:0]  O_seg_4,
    output wire [7:0]  O_seg_5         // 最高位
);

    //==========================================================================
    //  第 1 部分：把数值拆成"十位"和"个位"
    //    本系统的数值范围：亮度 0~31、对比度 0~31、周期 2~30，都 ≤ 99，
    //    所以两位十进制就够了。
    //    （除以常数 10 在综合时会被优化成移位加法，不占用除法器资源）
    //==========================================================================
    wire [15:0] val_div10 = I_value / 16'd10;
    wire [3:0]  d_tens    = val_div10[3:0];              // 十位
    wire [3:0]  d_ones    = (I_value % 16'd10);          // 个位

    //==========================================================================
    //  第 2 部分：决定每一位显示的"字符编码"（4bit，交给 seg_decoder 译码）
    //==========================================================================
    reg [3:0] dig5, dig4, dig3, dig2, dig1;

    // 字幕字符数拆成 百/十/个 三位（最多 512，三位够）
    wire [9:0] tl   = I_txt_len;
    wire [3:0] tl_h = tl / 10'd100;              // 百位
    wire [3:0] tl_t = (tl / 10'd10) % 10'd10;    // 十位
    wire [3:0] tl_o = tl % 10'd10;               // 个位

    always @(*) begin
        if (I_debug) begin
            //=========== 字幕调试画面（SW3 = ON）===========
            //   位5 位4  位3 位2 位1  位0
            //   状态 错误  百  十  个   横杠
            dig5 = I_txt_state;
            dig4 = {1'b0, I_txt_err};
            dig3 = tl_h;
            dig2 = tl_t;
            dig1 = tl_o;
        end else begin
            //=========== 正常画面 ===========
            // ---- 位 5：状态码（与原例程一致，方便对照排查）----
            dig5 = I_state_code;

            // ---- 位 4：模式指示 1=RUN, 2=ADJUST ----
            dig4 = I_adj_mode ? 4'd2 : 4'd1;

            // ---- 位 3：调节项 / 自动播放指示 ----
            if (I_adj_mode)
                dig3 = {2'b00, I_adj_sel} + 4'd1;   // 1=亮度 2=对比度 3=周期 4=缩放
            else
                dig3 = 4'hA;                        // 显示字母 A（Auto，自动轮播中）

            // ---- 位 2、位 1：数值 ----
            dig2 = d_tens;
            dig1 = d_ones;
        end
    end

    // 位 3 在"运行模式且自动轮播已关闭"时需要熄灭（调试模式下不熄灭）
    wire blank3 = (~I_adj_mode) & (~I_auto_play) & (~I_debug);

    //==========================================================================
    //  第 3 部分：例化 6 个 7 段译码器（复用工程自带的 seg_decoder）
    //    注意 seg_decoder 输出的是 7 位段码（不含小数点）
    //==========================================================================
    wire [6:0] s1, s2, s3, s4, s5;

    seg_decoder u_dec1 (.bin_data (dig1  ), .seg_data (s1));
    seg_decoder u_dec2 (.bin_data (dig2  ), .seg_data (s2));
    seg_decoder u_dec3 (.bin_data (dig3  ), .seg_data (s3));
    seg_decoder u_dec4 (.bin_data (dig4  ), .seg_data (s4));
    seg_decoder u_dec5 (.bin_data (dig5  ), .seg_data (s5));

    //==========================================================================
    //  第 4 部分：段码输出
    //    工程自带的 seg_decoder 只能译出 0~9 和 A~F，
    //    所以"横杠（减号）"和"熄灭"在这里直接用段码常量给出。
    //
    //    段码位序（与 seg_decoder 一致，低电平点亮）：
    //        bit6=g  bit5=f  bit4=e  bit3=d  bit2=c  bit1=b  bit0=a
    //    横杠 = 只点亮中间的 g 段 → g=0、其余全 1 → 7'b011_1111
    //    熄灭 = 所有段都灭        → 全 1         → 7'b111_1111
    //==========================================================================
    localparam [6:0] SEG_DASH  = 7'b011_1111;   // 横杠（减号）
    localparam [6:0] SEG_BLANK = 7'b111_1111;   // 全灭

    assign O_seg_0 = {1'b1, SEG_DASH};   // 最低位：横杠（作分隔符，比无意义的 0 更清爽）
    assign O_seg_1 = {1'b1, s1};
    assign O_seg_2 = {1'b1, s2};
    // 位 3：自动轮播关闭时显示横杠，比"完全熄灭"更能说明"此项处于关闭状态"
    assign O_seg_3 = blank3 ? {1'b1, SEG_DASH} : {1'b1, s3};
    assign O_seg_4 = {1'b1, s4};
    assign O_seg_5 = {1'b1, s5};

endmodule
