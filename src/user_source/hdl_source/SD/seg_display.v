//==============================================================================
//  文件名  : seg_display.v
//  模块名  : seg_display
//  功能    : 6 位数码管的显示内容合成
//------------------------------------------------------------------------------
//  【为什么要这个模块】
//  原例程只用数码管的最高位显示 bmp_read 的状态码，其余 5 位全灭。
//  改造后系统有了更多状态（运行/调节模式、当前参数、亮度值、周期…），
//  用一个模块统一组织显示内容，比在顶层里堆一堆 case 更清晰。
//
//  【显示版面（6 位，从 seg_data_5 到 seg_data_0）】
//
//   位   RUN 运行模式              ADJUST 调节模式
//   ---------------------------------------------------------------------
//    5   bmp_read 状态码            bmp_read 状态码
//        (1=空闲 2=扫描 3=等待 4=装载)  （与原例程保持一致，便于排查问题）
//   ---------------------------------------------------------------------
//    4   1 = 运行模式               2 = 调节模式
//   ---------------------------------------------------------------------
//    3   A = 自动轮播进行中         1/2/3 = 当前调节项
//        熄灭 = 自动轮播已关闭        1=亮度  2=对比度  3=轮播周期
//   ---------------------------------------------------------------------
//    2   数值十位                  数值十位
//    1   数值个位                  数值个位
//   ---------------------------------------------------------------------
//    0   常灭                      常灭
//
//  【数值显示的是什么】
//    RUN  模式：当前轮播周期（秒），例如 05 表示 5 秒
//    ADJUST 模式：当前调节项的数值（亮度 00~31 / 对比度 00~31 / 周期秒数）
//
//  【数码管电气特性（沿用工程原有约定）】
//    共阳数码管，段码低电平点亮：seg_data 的 bit[6:0] 为 7 段码，
//    bit[7] 是小数点（1 = 不亮）。整位熄灭时输出 8'hFF。
//    译码直接复用工程自带的 seg_decoder 模块（SD/seg_decoder.v）。
//------------------------------------------------------------------------------
//  所属工程: 基于安路 EG4S20 的智能数字广告牌系统（赛题一改造）
//  说明    : 详细中文注释版，供零基础队员阅读理解
//==============================================================================

module seg_display (
    // ---------------- 输入：要显示的信息 ----------------
    input  wire [3:0]  I_state_code,   // bmp_read 的状态码（沿用原例程功能）
    input  wire        I_adj_mode,     // 0 = RUN 运行模式，1 = ADJUST 调节模式
    input  wire [1:0]  I_adj_sel,      // 调节项 0=亮度 1=对比度 2=周期
    input  wire        I_auto_play,    // 自动轮播开关状态（1=正在自动轮播）
    input  wire [15:0] I_value,        // 要显示的数值（0..99）

    // ---------------- 输出：6 位数码管的段码 ----------------
    output wire [7:0]  O_seg_0,        // 最低位
    output wire [7:0]  O_seg_1,
    output wire [7:0]  O_seg_2,
    output wire [7:0]  O_seg_3,
    output wire [7:0]  O_seg_4,
    output wire [7:0]  O_seg_5         // 最高位
);

    //==========================================================================
    //  第 1 部分：把数值拆成"十位"和"个位"
    //    本系统的数值范围：亮度 0~31、对比度 0~31、周期 2~30，都 ≤ 99，
    //    所以两位十进制就够了。
    //    （除以常数 10 在综合时会被优化成移位加法，不占用除法器资源）
    //==========================================================================
    wire [15:0] val_div10 = I_value / 16'd10;
    wire [3:0]  d_tens    = val_div10[3:0];              // 十位
    wire [3:0]  d_ones    = (I_value % 16'd10);          // 个位

    //==========================================================================
    //  第 2 部分：决定每一位显示的"字符编码"（4bit，交给 seg_decoder 译码）
    //==========================================================================
    reg [3:0] dig5, dig4, dig3, dig2, dig1;

    always @(*) begin
        // ---- 位 5：状态码（与原例程一致，方便对照排查）----
        dig5 = I_state_code;

        // ---- 位 4：模式指示 1=RUN, 2=ADJUST ----
        dig4 = I_adj_mode ? 4'd2 : 4'd1;

        // ---- 位 3：调节项 / 自动播放指示 ----
        if (I_adj_mode)
            dig3 = {2'b00, I_adj_sel} + 4'd1;   // 1=亮度 2=对比度 3=周期
        else
            dig3 = 4'hA;                        // 显示字母 A（Auto，自动轮播中）

        // ---- 位 2、位 1：数值 ----
        dig2 = d_tens;
        dig1 = d_ones;
    end

    // 位 3 在"运行模式且自动轮播已关闭"时需要熄灭
    wire blank3 = (~I_adj_mode) & (~I_auto_play);

    //==========================================================================
    //  第 3 部分：例化 6 个 7 段译码器（复用工程自带的 seg_decoder）
    //    注意 seg_decoder 输出的是 7 位段码（不含小数点）
    //==========================================================================
    wire [6:0] s0, s1, s2, s3, s4, s5;

    seg_decoder u_dec0 (.bin_data (4'h0  ), .seg_data (s0));   // 最低位常显 0（占位）
    seg_decoder u_dec1 (.bin_data (dig1  ), .seg_data (s1));
    seg_decoder u_dec2 (.bin_data (dig2  ), .seg_data (s2));
    seg_decoder u_dec3 (.bin_data (dig3  ), .seg_data (s3));
    seg_decoder u_dec4 (.bin_data (dig4  ), .seg_data (s4));
    seg_decoder u_dec5 (.bin_data (dig5  ), .seg_data (s5));

    //==========================================================================
    //  第 4 部分：拼上小数点控制位（1 = 不亮），熄灭的位整字节给 8'hFF
    //==========================================================================
    assign O_seg_0 = {1'b1, s0};
    assign O_seg_1 = {1'b1, s1};
    assign O_seg_2 = {1'b1, s2};
    assign O_seg_3 = blank3 ? 8'hFF : {1'b1, s3};   // 需要熄灭时全灭
    assign O_seg_4 = {1'b1, s4};
    assign O_seg_5 = {1'b1, s5};

endmodule
