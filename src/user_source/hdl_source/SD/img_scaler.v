//==============================================================================
//  文件名  : img_scaler.v
//  模块名  : img_scaler
//  功能    : 任意尺寸 BMP → 640x480 自适应等比缩放（高度填满，左右补黑/裁切）
//------------------------------------------------------------------------------
//  【对应赛题】加分项③"图片自适应缩放"
//
//  【缩放规则（用户定的）】
//    ① 等比缩放，让**高度变成 480**
//    ② 缩放后宽度 = 源宽 x 480 / 源高
//    ③ 宽度 ≤ 640 → 居中显示，左右用黑色补齐
//       宽度 > 640 → 居中裁掉左右超出部分
//
//    例：1920x1080 → 853x480（左右各裁 107）
//        800x600   → 640x480（正好满屏）
//        1000x1000 → 480x480（左右各补 80 黑边）
//        200x150   → 640x480（放大 3.2 倍）
//
//  【核心算法：DDA 累加器，不用除法器】
//    横向（行内取样）：
//        每输出一个像素，累加器 += 源高
//        累加值 >= 480 就减掉 480 并把源列号 +1
//      —— 效果等于 "源列 = 输出列 x 源高 / 480"，但只用加减法 ✅
//
//    纵向（行重复/跳过）：
//        每收到一行源数据，累加器 += 480
//        累加值 >= 源高 就减掉源高，并把"这一行要输出的次数"+1
//      —— 放大时一行输出多次，缩小时某些源行输出 0 次 ✅
//
//  【为什么必须用行缓存】
//    纵向**放大**时，一行源数据要输出到多个目标行。而源数据是流式的，
//    流过去就没了 —— 所以必须先把整行存进 BRAM，再按需重复读取。
//    行缓存 = 2048 x 24bit ≈ 6 块 ERAM（本工程还剩十几块，够用）。
//
//  【已知限制 —— 重要】
//    源图像素是以"突发"方式来的（一个 SD 扇区 512 字节 = 170 个像素，
//    连续 512 拍送完），而输出是每拍 1 个像素。所以：
//        放大倍率 > 3 倍时，输出会跟不上输入，可能丢像素。
//    实际广告素材（≥213x160）都在安全范围内。
//    如果你要放很小的图（比如 100x75），告诉我，我给 SD 读取加反压。
//------------------------------------------------------------------------------
//  所属工程: 基于安路 EG4S20 的智能数字广告牌系统（赛题一改造）
//==============================================================================

module img_scaler (
    input  wire        clk,             // sd_card_clk = 100MHz
    input  wire        rst,

    // ---------------- 输入：来自 bmp_read 的源图像素流 ----------------
    input  wire        I_wr,            // 像素有效
    input  wire [23:0] I_data,          // 像素颜色
    input  wire [15:0] I_w,             // 源图宽度
    input  wire [15:0] I_h,             // 源图高度
    input  wire        I_frame_start,   // 新图第一个像素（复位内部计数）

    // ---------------- 输出：640x480 像素流（含黑边，行优先）----------------
    output reg         O_wr,            // 输出像素有效
    output reg  [23:0] O_data,          // 输出像素颜色
    output reg         O_done           // 一整帧 480 行输出完毕
);

    //==========================================================================
    //  参数
    //==========================================================================
    localparam [15:0] DST_W = 16'd640;   // 输出帧宽
    localparam [15:0] DST_H = 16'd480;   // 输出帧高
    localparam [11:0] LBUF_DEPTH = 12'd2048;

    localparam [2:0] S_IDLE = 3'd0;   // 等新图
    localparam [2:0] S_CALC = 3'd1;   // 算缩放后宽度 W_dst 和居中起点 x0
    localparam [2:0] S_FILL = 3'd2;   // 收一行源数据进行缓存
    localparam [2:0] S_EMIT = 3'd3;   // 输出目标行（可能重复多次）
    localparam [2:0] S_DONE = 3'd4;   // 480 行输出完

    reg [2:0] state;

    //==========================================================================
    //  行缓存：存一整行源数据
    //    只按"变量地址"读写（写用 col，读用 rd_col），TD 才能识别成块 RAM。
    //    ★ 千万不要写 lbuf[0] 这种常量地址读，会让 TD 摊成触发器+巨型多路器，
    //      布局直接失败（这个坑在 txt_read.v 里踩过一次）。
    //==========================================================================
    reg [23:0] lbuf [0:2047];

    //==========================================================================
    //  内部寄存器
    //==========================================================================
    reg [15:0] col;         // 收行时的源列号 0..I_w-1
    reg [15:0] src_row;     // 当前是第几行源数据
    reg [15:0] dst_row;     // 当前输出到第几行（0..479）

    reg [15:0] w_dst;       // 缩放后宽度
    reg [15:0] x0;          // 图像在 640 宽里的起始列（居中）
    reg        clip;        // 1 = 图像比 640 宽，要裁切

    // ---- 横向 DDA ----
    reg [31:0] h_acc;       // 累加器 = 源列 x 480 的余数部分
    reg [15:0] h_col;       // 当前取样到第几列

    // ---- 纵向 DDA ----
    reg [31:0] v_acc;
    reg [15:0] v_rep;       // 这一行源数据要输出几次
    reg [15:0] v_done;      // 这一行已经输出了几次

    // ---- 输出行内的位置 ----
    reg [15:0] dx;          // 正在输出第几个像素 0..639
    reg [15:0] px;          // 实际取样的源列（= x0 之前为黑边）

    reg [31:0] calc_num;    // 除法用的被除数
    reg [31:0] calc_quo;    // 商

    //==========================================================================
    //  第 1 部分：算缩放后宽度 W_dst = I_w * 480 / I_h
    //
    //    只在换图时算一次，所以用最笨的"重复减法"完全够用，不用综合除法器。
    //    最坏情况（I_h=1，I_w=2048）约 98 万次循环 = 10ms，一次性开销可接受。
    //==========================================================================
    wire [31:0] calc_rem = calc_num - {16'b0, I_h};

    //==========================================================================
    //  第 2 部分：主状态机
    //==========================================================================
    integer k;

    always @(posedge clk or posedge rst) begin
        if (rst) begin
            state    <= S_IDLE;
            col      <= 16'd0;
            src_row  <= 16'd0;
            dst_row  <= 16'd0;
            w_dst    <= 16'd0;
            x0       <= 16'd0;
            clip     <= 1'b0;
            h_acc    <= 32'd0;
            h_col    <= 16'd0;
            v_acc    <= 32'd0;
            v_rep    <= 16'd0;
            v_done   <= 16'd0;
            dx       <= 16'd0;
            px       <= 16'd0;
            calc_num <= 32'd0;
            calc_quo <= 32'd0;
            O_wr     <= 1'b0;
            O_data   <= 24'd0;
            O_done   <= 1'b0;
        end else begin
            O_wr   <= 1'b0;      // 默认不输出，只在需要时拉高一拍
            O_done <= 1'b0;

            case (state)

                //==========================================================
                //  等新图开始
                //==========================================================
                S_IDLE: begin
                    dst_row <= 16'd0;
                    src_row <= 16'd0;
                    col     <= 16'd0;
                    if (I_frame_start) begin
                        // 开始算 W_dst = I_w * 480 / I_h
                        calc_num <= {16'b0, I_w} * 32'd480;
                        calc_quo <= 32'd0;
                        state    <= S_CALC;
                    end
                end

                //==========================================================
                //  重复减法算除法：W_dst = I_w*480 / I_h
                //==========================================================
                S_CALC: begin
                    if (calc_num < {16'b0, I_h}) begin
                        // 除完了
                        w_dst <= calc_quo[15:0];
                        // 算居中起点 x0 = (640 - W_dst) / 2
                        if (calc_quo[15:0] >= DST_W) begin
                            clip <= 1'b1;
                            x0   <= (calc_quo[15:0] - DST_W) >> 1;   // 要裁掉的左边宽度
                        end else begin
                            clip <= 1'b0;
                            x0   <= (DST_W - calc_quo[15:0]) >> 1;   // 左边补多少黑
                        end
                        col      <= 16'd0;
                        src_row  <= 16'd0;
                        dst_row  <= 16'd0;
                        v_acc    <= 32'd0;
                        state    <= S_FILL;
                    end else begin
                        calc_num <= calc_rem;
                        calc_quo <= calc_quo + 32'd1;
                    end
                end

                //==========================================================
                //  收一行源数据进缓存
                //==========================================================
                S_FILL: begin
                    if (I_wr) begin
                        lbuf[col[10:0]] <= I_data;
                        col <= col + 16'd1;
                        if (col + 16'd1 >= I_w) begin
                            // ---- 一整行收完，算这行要输出几次 ----
                            col <= 16'd0;
                            // 纵向 DDA：这一行覆盖多少个目标行
                            //   累加 480，每满 I_h 就多输出一行
                            begin : v_dda
                                reg [31:0] a;
                                reg [15:0] n;
                                a = v_acc;
                                n = 16'd0;
                                for (k = 0; k < 32; k = k + 1) begin
                                    if (a >= {16'b0, I_h}) begin
                                        a = a - {16'b0, I_h};
                                        n = n + 16'd1;
                                    end
                                end
                                v_acc  <= a;
                                v_rep  <= n;
                            end
                            v_done <= 16'd0;
                            dx     <= 16'd0;
                            h_acc  <= 32'd0;
                            h_col  <= 16'd0;
                            state  <= S_EMIT;
                        end
                    end
                end

                //==========================================================
                //  输出目标行（同一行可能输出多次 —— 纵向放大）
                //    每个像素的位置分三段：
                //        [0, x0)              → 黑边（左）
                //        [x0, x0+span)        → 从行缓存取样
                //        [x0+span, 640)       → 黑边（右）
                //    clip=1 时 x0 表示"要裁掉左边的宽度"，源列直接从 x0 开始数
                //==========================================================
                S_EMIT: begin
                    // 本行还要不要输出
                    if (v_done >= v_rep) begin
                        // 这一行源数据输出完了 → 收下一行源数据
                        src_row <= src_row + 16'd1;
                        state   <= S_FILL;
                    end else if (dx == DST_W) begin
                        // 一行 640 个像素输出完了
                        dx     <= 16'd0;
                        h_acc  <= 32'd0;
                        h_col  <= 16'd0;
                        v_done <= v_done + 16'd1;
                        dst_row<= dst_row + 16'd1;
                        // 480 行都输出完 → 整帧结束
                        if (dst_row + 16'd1 >= DST_H) begin
                            O_done <= 1'b1;
                            state  <= S_DONE;
                        end
                    end else begin
                        // ---- 输出第 dx 个像素 ----
                        O_wr <= 1'b1;
                        if (!clip) begin
                            // 居中模式：x0 是左边黑边宽度
                            if (dx < x0) begin
                                O_data <= 24'h000000;          // 左黑边
                                h_acc  <= 32'd0;
                                h_col  <= 16'd0;
                            end else if (dx >= (x0 + w_dst)) begin
                                O_data <= 24'h000000;          // 右黑边
                            end else begin
                                // 图像区域：用 DDA 取样
                                O_data <= lbuf[h_col[10:0]];
                                h_acc  <= h_acc + {16'b0, I_h};
                                if ((h_acc + {16'b0, I_h}) >= 32'd480) begin
                                    h_acc <= h_acc + {16'b0, I_h} - 32'd480;
                                    h_col <= h_col + 16'd1;
                                end
                            end
                        end else begin
                            // 裁切模式：图像比屏幕宽，中间取样
                            //   源列 = x0 + dx
                            px = x0 + dx;
                            if ((x0 + dx) >= I_w) begin
                                O_data <= 24'h000000;
                            end else begin
                                O_data <= lbuf[(x0 + dx)];
                            end
                        end
                        dx <= dx + 16'd1;
                    end
                end

                //==========================================================
                //  整帧输出完，等下一次 I_frame_start
                //==========================================================
                S_DONE: begin
                    if (I_frame_start) begin
                        calc_num <= {16'b0, I_w} * 32'd480;
                        calc_quo <= 32'd0;
                        dst_row  <= 16'd0;
                        src_row  <= 16'd0;
                        state    <= S_CALC;
                    end
                end

                default: state <= S_IDLE;
            endcase
        end
    end

endmodule
