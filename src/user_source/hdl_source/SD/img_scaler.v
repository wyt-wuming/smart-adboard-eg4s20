//==============================================================================
//  文件名  : img_scaler.v
//  模块名  : img_scaler
//  功能    : 任意尺寸 BMP → 640x480 自适应等比缩放（高度填满，左右补黑/裁切）
//  时钟域  : sd_card_clk（100MHz）
//------------------------------------------------------------------------------
//  【对应赛题】加分项③"图片自适应缩放"
//
//  【缩放规则】
//    ① 等比缩放，让**高度变成 480**
//    ② 缩放后宽度 W_dst = 源宽 x 480 / 源高
//    ③ W_dst ≤ 640 → 居中显示，左右用黑色补齐
//       W_dst > 640 → 居中裁掉左右超出部分
//
//    例：1920x1080 → 853x480（左右各裁 107）
//        800x600   → 640x480（正好满屏）
//        1000x1000 → 480x480（左右各补 80 黑边）
//        200x150   → 640x480（放大 3.2 倍）
//
//------------------------------------------------------------------------------
//  【核心算法：两个"比较式 DDA"，全程只有加减法和比较，零乘除法】
//
//    ── 纵向 ──   目标行 dy 该用哪一行源数据？
//        定义两个累加器：  w_acc = dy x 源高        （每输出一行 +源高）
//                          s_acc = (sy+1) x 480     （每收完一行源数据 +480）
//        判据： w_acc < s_acc  →  第 dy 行要用第 sy 行源数据
//
//        为什么这样写？—— 它等价于 dy/sy 的等比映射，但**不需要除法**。
//        而且判据天然处理了三种情况：
//            源图更高（缩小）→ 收好几行源数据才输出一行 ✓
//            源图更矮（放大）→ 收一行源数据要输出好几行 ✓
//            高度正好 480   → 一行对一行 ✓
//
//    ── 横向 ──   输出像素 dx 该取哪一列源数据？
//        同样两个累加器：  h_acc = (dx - pad_left) x 源高   （每输出一个图像像素 +源高）
//                          c_acc = (sx+1) x 480             （每取完一列源数据 +480）
//        判据： h_acc >= c_acc  →  源列 sx 前进一列
//
//  【行缓存：为什么必须有】
//    纵向**放大**时，一行源数据要重复输出到多个目标行；而源数据是流式的、
//    过去就没了 —— 所以必须先把整行存进 BRAM，再按需重复读取。
//    长度 2048 x 24bit，按变量地址读写（常量地址读会让 TD 摊成触发器阵列，
//    布局必然失败 —— 这个坑在 txt_read.v 里踩过一次）。
//
//  【已知限制】
//    源像素以突发方式到达（一个 SD 扇区 512 字节 = 170 像素），而输出是每拍 1 像素。
//    放大倍率超过约 3 倍时输出会跟不上输入。
//    广告素材（≥213x160）都在安全范围内。
//
//------------------------------------------------------------------------------
//  【★ 关键时序约束：源像素流"不能暂停，也不能丢"】
//
//    bmp_read 是"读到一个像素就往外吐一个"，它没有 ready/暂停接口 ——
//    **只要 I_wr 来了而本模块没接住，这个像素就永远丢了**，
//    后果是行边界错位 → 整幅图变成"斜的"（越往下越偏）。
//
//    源像素的实际到达速率（实测换算）：
//       SD 走 SPI 25MHz，一个字节约 35 拍 @100MHz → 一个像素(3字节)约 106 拍
//       → 一整行 640 像素要 6.8 万拍（约 0.68ms）
//    而本模块输出一行只花 640 拍 —— 也就是说，
//    **随便一个"输出行"的状态都会持续 640 拍，期间必然会漏掉约 6 个源像素。**
//
//    【旧版的漏洞】旧版只在 S_FILL 状态里用 I_wr 往行缓存写数据，
//    一旦进入 S_EMIT（输出 640 拍）就完全不管输入 → 每行丢 6 个像素，
//    整幅图逐行右移，480 行累计错位约 4~5 行（肉眼可见的"斜切/撕裂"）。
//    缩小(zoom<100)时更严重：屏幕上下黑边一共有 120 行 = 76800 拍，
//    期间到达的约 680 个源像素会全部丢掉 → 画面彻底花掉。
//
//    【本版的解决办法：行缓存改成"循环原始缓冲"，输入永不丢】
//      · 写侧：只要 I_wr 有效就写 lbuf[wp]、wp++，**与状态机完全无关**；
//        换图时（I_frame_start）写指针清零，第一个像素落在 lbuf[0]。
//      · 读侧：第 sy 行的数据就躺在 lbuf[rb .. rb+I_w-1]（rb = 行基址，
//        每取一行 rb += I_w，11 位自然回绕 = 模 2048）。
//      · 状态机只在"要用这一行"时等一个"整行到齐"条件（occ ≥ I_w），
//        其它时间哪怕在输出黑边、在算缩放比例，数据也照样收进缓冲。
//
//      这样占用仍然是同一块 2048x24 行缓存（不额外吃 BRAM），
//      但输入侧最多可以"攒下"整块缓冲的数据：
//        最坏情况 = 缩小到 50% 时的上黑边(120 行 = 76800 拍) → 约 680 个像素，
//        远小于 2048，不会把还没读的行冲掉。
//      （代价：同一行不能被输出两次以上……这一点由 DDA 保证，本来就成立）
//==============================================================================

module img_scaler (
    input  wire        clk,             // sd_card_clk = 100MHz
    input  wire        rst,

    // ---------------- 输入：来自 bmp_read 的源图像素流 ----------------
    input  wire        I_wr,            // 像素有效
    input  wire [23:0] I_data,          // 像素颜色
    input  wire [15:0] I_w,             // 源图宽度
    input  wire [15:0] I_h,             // 源图高度
    input  wire        I_frame_start,   // 新图第一个像素（复位内部状态）
    input  wire [7:0]  I_zoom,          // ★ 缩放百分比 50~200（100 = 原图大小）

    // ---------------- 输出：640x480 像素流（含黑边，行优先）----------------
    output reg         O_wr,            // 输出像素有效
    output reg  [23:0] O_data,          // 输出像素颜色
    output reg         O_done           // 一整帧 480 行输出完毕
);

    localparam [15:0] DST_W = 16'd640;
    localparam [15:0] DST_H = 16'd480;

    //==========================================================================
    //  ★ 输出分频（2026-10-06 新增）
    //    本模块在 S_EMIT 状态是"1 拍吐 1 个像素"的突发式输出，
    //    连续 640 拍就能吐完整整一行；而下游的写 FIFO（wfifo_32_32_512）
    //    深度只有 512 —— 640 > 512，**FIFO 会被写爆，像素直接丢**，
    //    表现为画面横条纹 + 写不满一帧导致永远不切换。
    //    原来的设计没问题，是因为 bmp_read 的输出速率只有约 106 拍/像素
    //    （SPI 读卡慢），FIFO 有的是时间排空；插入缩放器后输出变成了突发。
    //    这里把输出降速到每 EMIT_DIV+1 拍一个像素：
    //      25 MHz @100MHz 时钟 → 远低于 SDRAM 写入能力，FIFO 再也不会满；
    //      而输出一整帧只要 307200 x 4 = 123 万拍 ≈ 12 ms，
    //      相比源数据到达需要的 ~326 ms 仍然快得多，不影响装载速度。
    //==========================================================================
    localparam [1:0] EMIT_DIV = 2'd3;      // 3 = 每 4 拍输出一个像素

    localparam [2:0] S_IDLE = 3'd0;   // 等新图
    localparam [2:0] S_WD   = 3'd1;   // 算缩放后宽度 W_dst
    localparam [2:0] S_SKIP = 3'd2;   // 算裁切时要跳过的源列（含 DDA 初值）
    localparam [2:0] S_FILL = 3'd3;   // 收一行源数据进缓存
    localparam [2:0] S_NEXT = 3'd4;   // 判断：本行源数据还要不要再输出一行
    localparam [2:0] S_EMIT = 3'd5;   // 输出一整行 640 像素
    localparam [2:0] S_DONE = 3'd6;   // 整帧输出完
    localparam [2:0] S_HD   = 3'd7;   // ★ 先算缩放后图像高度 H_dst = zoom x 24 / 5

    reg [2:0] state;

    //==========================================================================
    //  行缓存（2048 x 24bit，按变量地址读写 → 综合成块 RAM）
    //    ★ 现在它是"循环原始缓冲"：写入只跟 I_wr 走（见下面的写侧），
    //      读的时候用 "行基址 rb + 行内列号 sx"，11 位自然回绕。
    //==========================================================================
    reg [23:0] lbuf [0:2047];

    //==========================================================================
    //  预计算结果（每次换图算一次）
    //==========================================================================
    reg [15:0] w_dst;      // 缩放后宽度
    reg [15:0] pad_left;   // 左边补黑宽度
    reg [15:0] img_end;    // 图像右边界（可 > 640，表示溢出被裁）
    reg [15:0] sx0;        // 横向 DDA 起始源列（裁切时 >0）
    reg [31:0] ha0;        // 横向 DDA 起始累加值
    reg [31:0] ca0;        // 横向 DDA 起始比较值

    // ---- ★ 画面缩放相关 ----
    //   H_dst = 480 x zoom / 100   —— 缩放后图像的高度
    //   top_pad / img_bot  —— 上下黑边的边界
    //   w_acc_init —— 纵向 DDA 的初值（放大时头部要跳过的源行）
    reg [15:0] h_dst;        // 缩放后图像高度
    reg [15:0] top_pad;      // 上边黑边高度（仅 H_dst<480 时有效）
    reg        top_has_pad;  // 1 = 上面有黑边
    reg [15:0] img_bot;      // 图像下边界 = (480+H_dst)/2
    reg [31:0] w_acc_init;   // 纵向 DDA 初值
    reg        black_row;    // 当前输出的是"整行黑"（上下黑边）

    //==========================================================================
    //  运行时寄存器
    //==========================================================================
    // ★ 原来这里有个 col（收行时的源列号）—— 现在写侧由 wp 自动推进，
    //   不再需要它了（数据一进缓冲就有位置，行号由 rb 记录）
    reg [15:0] sy;         // 当前收的是第几行源数据
    reg [15:0] dy;         // 当前输出到第几行

    reg [31:0] w_acc;      // 纵向：dy x 源高
    reg [31:0] s_acc;      // 纵向：(sy+1) x 480

    reg [15:0] dx;         // 行内输出像素号
    reg [31:0] h_acc;      // 横向：(dx-pad_left) x 源高
    reg [31:0] c_acc;      // 横向：(sx+1) x 480
    reg [15:0] sx;         // 横向当前源列
    reg [1:0]  emit_div;   // ★ 输出分频计数器（0 = 本拍可以吐像素）

    // 定点换算的临时量（重复减法，只在换图时用一次）
    reg [31:0] tmp_num;
    reg [31:0] tmp_quo;

    integer k;

    // ★【安全保护】如果 I_zoom 还没接上（悬空读成 0），按 100% 处理。
    //   否则 H_dst 会算成 0，整个画面全黑 —— 这个保护让"没接线"也能正常工作。
    wire [7:0] zoom_use = (I_zoom < 8'd50) ? 8'd100 : I_zoom;

    //==========================================================================
    //  ★ 写侧：无条件收下每一个源像素（绝不丢像素）
    //    wp = 写指针（11 位，0~2047 循环）
    //    rb = 行基址（第 sy 行数据在缓冲里的起点，每取一行 +I_w）
    //    两者都是"模 2048 的计数器"，(wp-rb) 就是缓冲里攒了多少像素
    //    ★ 注意：下面用到的 sx 必须在前面已经声明（本文件上方已声明），
    //      否则 TD 会按 1 位"隐式线网"处理（HDL-7225）。
    //==========================================================================
    reg [10:0] wp;         // 写指针
    reg [10:0] rb;         // 当前行(sy 行)在缓冲里的基址

    wire [10:0] wr_ptr = I_frame_start ? 11'd0 : wp;   // 换图第一拍写 0 号位置
    // 读地址：行基址 + 行内列号（11 位相加，自动模 2048）
    wire [10:0] rd_addr = rb + sx[10:0];
    // 缓冲里已攒下多少像素（前提：攒下的量 < 2048，见文件头的说明）
    wire [10:0] occ     = wp - rb;
    // "当前这一行已经整行到齐" —— 状态机据此决定能不能开始输出
    wire        row_ready = (I_w[10:0] == 11'd0) || (occ >= I_w[10:0]);

    always @(posedge clk or posedge rst) begin
        if (rst) begin
            wp <= 11'd0;
        end else if (I_frame_start) begin
            wp <= 11'd1;                  // 第一个像素写在 lbuf[0]
        end else if (I_wr) begin
            wp <= wp + 11'd1;
        end
    end

    // 写入与状态机完全无关：只要源像素有效就收（这是"不丢像素"的关键）
    always @(posedge clk) begin
        if (I_wr)
            lbuf[wr_ptr] <= I_data;
    end

    //==========================================================================
    //  横向 DDA 的"前进多少列"组合逻辑
    //    一次最多跨 ceil(2048/480)=5 列，用 8 次小循环就够
    //
    //  ★【重要】临时变量必须声明在**模块层级**：
    //    Verilog-2001 不允许在"未命名的 begin...end 块"里声明变量
    //    （只有 SystemVerilog 才允许），安路 TD 会直接报
    //      HDL-8007: declarations are not allowed in an unnamed block
    //    这个坑在本文件编译时踩过一次（原来的写法就是块内声明）。
    //    要写"块内局部变量"就必须给块起名字（begin : 块名），否则免谈。
    //==========================================================================
    reg [31:0] dda_a;      // 本像素走完后 h_acc 的值
    reg [31:0] dda_cc;     // 当前 (源列+1) x H_dst
    reg [15:0] dda_nn;     // 当前源列
    reg [15:0] sx_next;
    reg [31:0] c_acc_next;
    always @(*) begin
        dda_a  = h_acc + {16'b0, I_h};
        dda_cc = c_acc;
        dda_nn = sx;
        // 只要 dda_a >= (nn+1)xH_dst 就说明该源列已经被覆盖完，前进一列
        // 一次最多跨 5 列（源高 2048 / 480），循环 8 次足够
        for (k = 0; k < 8; k = k + 1) begin
            if (dda_a >= dda_cc) begin
                dda_nn = dda_nn + 16'd1;
                dda_cc = dda_cc + {16'b0, h_dst};
            end
        end
        sx_next    = dda_nn;
        c_acc_next = dda_cc;
    end

    //==========================================================================
    //  主状态机
    //==========================================================================
    always @(posedge clk or posedge rst) begin
        if (rst) begin
            state   <= S_IDLE;
            rb      <= 11'd0;
            sy      <= 16'd0;
            dy      <= 16'd0;
            w_acc   <= 32'd0;
            s_acc   <= 32'd0;
            dx      <= 16'd0;
            h_acc   <= 32'd0;
            c_acc   <= 32'd0;
            sx      <= 16'd0;
            emit_div<= 2'd0;
            w_dst   <= 16'd0;
            pad_left<= 16'd0;
            img_end <= 16'd0;
            sx0     <= 16'd0;
            ha0     <= 32'd0;
            ca0     <= 32'd0;
            tmp_num <= 32'd0;
            tmp_quo <= 32'd0;
            O_wr    <= 1'b0;
            O_data  <= 24'd0;
            O_done  <= 1'b0;
        end else begin
            O_wr   <= 1'b0;
            O_done <= 1'b0;

            case (state)

                //==========================================================
                //  等新图
                //==========================================================
                S_IDLE: begin
                    sy    <= 16'd0;
                    dy    <= 16'd0;
                    w_acc <= 32'd0;
                    s_acc <= 32'd0;
                    rb    <= 11'd0;          // ★ 行基址归零（与写指针 wp 对齐）
                    if (I_frame_start) begin
                        // ★ 第一步先算 H_dst = zoom x 480 / 100 = zoom x 24 / 5
                        tmp_num <= {24'b0, zoom_use} * 32'd24;
                        tmp_quo <= 32'd0;
                        state   <= S_HD;
                    end
                end

                //==========================================================
                //  ★ 先算缩放后图像高度：H_dst = zoom x 24 / 5
                //    zoom=100 → 480；zoom=50 → 240；zoom=200 → 960
                //==========================================================
                S_HD: begin
                    if (tmp_num < 32'd5) begin
                        h_dst <= tmp_quo[15:0];
                        // 上下黑边边界
                        //   上边界(图像顶边) = (480 - H_dst)/2，为负时表示上方被裁
                        //   下边界 = (480 + H_dst)/2   —— 两种情况都适用
                        if (tmp_quo[15:0] < DST_H) begin
                            top_has_pad <= 1'b1;
                            top_pad     <= (DST_H - tmp_quo[15:0]) >> 1;
                            // 图像区从第 top_pad 行开始，w_acc 从 0 起
                            w_acc_init  <= 32'd0;
                        end else begin
                            top_has_pad <= 1'b0;
                            top_pad     <= 16'd0;
                            // H_dst>480：头顶被裁掉 (H_dst-480)/2 行源数据
                            w_acc_init  <= (((tmp_quo[15:0] - DST_H) >> 1) * {16'b0, I_h});
                        end
                        img_bot <= (DST_H + tmp_quo[15:0]) >> 1;
                        // 下一步算源图宽度映射：w_dst = I_w x H_dst / I_h
                        tmp_num <= {16'b0, I_w} * {16'b0, tmp_quo[15:0]};
                        tmp_quo <= 32'd0;
                        state   <= S_WD;
                    end else begin
                        tmp_num <= tmp_num - 32'd5;
                        tmp_quo <= tmp_quo + 32'd1;
                    end
                end

                //==========================================================
                //  W_dst = I_w x 480 / I_h      （重复减法，换图时算一次）
                //==========================================================
                S_WD: begin
                    if (tmp_num < {16'b0, I_h}) begin
                        w_dst <= tmp_quo[15:0];
                        // 算 pad_left / img_end，并准备好"要跳过多少像素"的被除数
                        if (tmp_quo[15:0] >= DST_W) begin
                            // 比 640 宽 → 居中裁切，左边不补黑
                            pad_left <= 16'd0;
                            img_end  <= tmp_quo[15:0];
                            // 要跳过的源列 = (W_dst-640)/2 个输出像素对应的源列
                            tmp_num  <= ((tmp_quo[15:0] - DST_W) >> 1) * {16'b0, I_h};
                        end else begin
                            pad_left <= (DST_W - tmp_quo[15:0]) >> 1;
                            img_end  <= ((DST_W - tmp_quo[15:0]) >> 1) + tmp_quo[15:0];
                            tmp_num  <= 32'd0;      // 不裁切，不用跳
                        end
                        tmp_quo <= 32'd0;
                        state   <= S_SKIP;
                    end else begin
                        tmp_num <= tmp_num - {16'b0, I_h};
                        tmp_quo <= tmp_quo + 32'd1;
                    end
                end

                //==========================================================
                //  算横向 DDA 的起点（裁切时把起点推到中间去）
                //    tmp_num 里装的是 (跳过像素数 x 源高)
                //    除以 480：商 = 起始源列 sx0，余数 = 起始累加值 ha0
                //==========================================================
                S_SKIP: begin
                    if (tmp_num < {16'b0, h_dst}) begin
                        sx0 <= tmp_quo[15:0];
                        ha0 <= tmp_num;
                        ca0 <= {16'b0, h_dst};   // (sx0+1) x H_dst
                        w_acc <= w_acc_init;     // ★ 纵向 DDA 初值（放大时头部要跳源行）
                        state <= S_FILL;
                    end else begin
                        tmp_num <= tmp_num - {16'b0, h_dst};
                        tmp_quo <= tmp_quo + 32'd1;
                    end
                end

                //==========================================================
                //  等"当前这一行(sy 行)整行到齐"
                //    ★ 数据和写入行缓存已经由写侧自动完成（见文件头说明），
                //      这里只等数量够：缓冲里攒下的像素 occ >= I_w，
                //      就说明第 sy 行已完整躺在 lbuf[rb .. rb+I_w-1] 里。
                //==========================================================
                S_FILL: begin
                    if (row_ready) begin
                        s_acc <= s_acc + {16'b0, h_dst};   // (sy+1) x H_dst
                        state <= S_NEXT;
                    end
                end

                //==========================================================
                //  判断：本行源数据还要不要再输出一行？
                //    判据  w_acc < s_acc  →  要
                //    这里的两个累加器就是"纵向 DDA"，全程只有加减法和比较
                //==========================================================
                S_NEXT: begin
                    if (dy >= DST_H) begin
                        // 480 行全部输出完 → 整帧结束
                        O_done <= 1'b1;
                        state  <= S_DONE;
                    end else if (top_has_pad && (dy < top_pad)) begin
                        // ---- ★ 上方黑边（缩小时才有）：整行黑，不碰行缓存 ----
                        black_row <= 1'b1;
                        dx        <= 16'd0;
                        state     <= S_EMIT;
                    end else if (dy >= img_bot) begin
                        // ---- ★ 下方黑边 ----
                        black_row <= 1'b1;
                        dx        <= 16'd0;
                        state     <= S_EMIT;
                    end else if (sy >= I_h) begin
                        // 源数据用完（正常算不会走到，保底）
                        black_row <= 1'b1;
                        dx        <= 16'd0;
                        state     <= S_EMIT;
                    end else if (w_acc < s_acc) begin
                        // 本行源数据要输出 → 进入取样输出
                        black_row <= 1'b0;
                        dx    <= 16'd0;
                        h_acc <= ha0;
                        c_acc <= ca0;
                        sx    <= sx0;
                        state <= S_EMIT;
                    end else begin
                        // 本行源数据不再需要 → 取下一行源数据
                        //   ★ 行基址前进一整行（下一行的数据在缓冲里紧挨着）
                        sy    <= sy + 16'd1;
                        rb    <= rb + I_w[10:0];
                        state <= S_FILL;
                    end
                end

                //==========================================================
                //  输出一整行 640 像素
                //    [0, pad_left)          → 左黑边
                //    [pad_left, img_end)    → 从行缓存取样（用横向 DDA）
                //    [img_end, 640)         → 右黑边
                //    img_end > 640 时，右边自然被裁掉（多出来的不输出）
                //==========================================================
                S_EMIT: begin
                    if (dx >= DST_W) begin
                        // 一行输出完 → 目标行 +1，回 S_NEXT 判断要不要再来一行
                        dy <= dy + 16'd1;
                        // ★ 只有"真正的图像行"才推进纵向 DDA；
                        //   上下黑边只是填黑，不能动累加器，否则映射会错位
                        if (!black_row) w_acc <= w_acc + {16'b0, I_h};
                        state <= S_NEXT;
                    end else if (emit_div != 2'd0) begin
                        // ★ 输出分频的等待拍：本拍不产生 O_wr，给写 FIFO 留排空时间
                        emit_div <= emit_div - 2'd1;
                    end else begin
                        emit_div <= EMIT_DIV;   // ★ 吐完这个像素后，再等 EMIT_DIV 拍
                        if (black_row) begin
                            // ---- 上下黑边：整行直接输出黑，不用取样 ----
                            O_wr   <= 1'b1;
                            O_data <= 24'h000000;
                            dx     <= dx + 16'd1;
                        end else begin
                            O_wr <= 1'b1;
                            if ((dx < pad_left) || (dx >= img_end)) begin
                                O_data <= 24'h000000;              // 黑边
                            end else begin
                                // ★ 取样地址 = 行基址 rb + 行内列号 sx（模 2048）
                                O_data <= lbuf[rd_addr];
                            end
                            // 横向 DDA 前进（只有图像区域内才需要推进）
                            if ((dx >= pad_left) && (dx < img_end)) begin
                                h_acc <= h_acc + {16'b0, I_h};
                                sx    <= sx_next;
                                c_acc <= c_acc_next;
                            end
                            dx <= dx + 16'd1;
                        end
                    end
                end

                //==========================================================
                //  整帧输出完，等下一次 I_frame_start
                //==========================================================
                S_DONE: begin
                    sy      <= 16'd0;
                    dy      <= 16'd0;
                    w_acc   <= 32'd0;
                    s_acc   <= 32'd0;
                    rb      <= 11'd0;            // ★ 行基址归零，与写指针 wp 对齐
                    if (I_frame_start) begin
                        // ★ 这里必须和 S_IDLE 走完全相同的流程：
                        //   先 S_HD 重算 H_dst（缩放值可能已经变了），再 S_WD。
                        //   旧版这里直接跳 S_WD 且用写死的 480 算 w_dst，
                        //   导致第 2 张图之后的缩放比例、黑边全都算错 ——
                        //   第 1 张图正常、往后每张都变形，很难查。
                        tmp_num <= {24'b0, zoom_use} * 32'd24;
                        tmp_quo <= 32'd0;
                        state   <= S_HD;
                    end
                end

                default: state <= S_IDLE;
            endcase
        end
    end

endmodule
