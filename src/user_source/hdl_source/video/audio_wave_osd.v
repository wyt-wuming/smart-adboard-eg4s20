//==============================================================================
//  文件名  : audio_wave_osd.v
//  模块名  : audio_wave_osd
//  功能    : 在屏幕中下方（移动字幕上方）叠加绿色音频波形图
//  时钟域  : video_clk（25MHz）
//------------------------------------------------------------------------------
//  【显示效果】
//
//      ┌──────────────────────────────────────────────┐
//      │              广告画面 640x480                  │
//      │          ~~~ 绿色波形（随音乐抖动）~~~          │  ← y=403~433
//      ├──────────────────────────────────────────────┤  ← 字幕底条 y=440 起
//      │            安路科技 广告牌 欢迎光临             │
//      └──────────────────────────────────────────────┘
//
//      波形区：x = 64 ~ 575（512 列，居中），中心线 y = 418
//      每列是波形的一段（128 个 48kHz 采样的峰值，约 2.67ms）
//      512 列 = 约 1.37 秒的波形窗口，从右向左滚动
//      颜色：纯绿（24'h00FF00），每列 1 像素宽的竖线（细线）
//
//  【为什么按列取峰值，而不是直接画原始采样】
//      48kHz 原始采样直接画到 512 列上，会变成一片高频噪点，
//      什么也看不出来；按列取峰值后，波形呈现音乐的真实起伏
//      （鼓点、人声、副歌都能看出来），这才是"随音乐抖动"的效果。
//
//  【静音表现（用户明确要求）】
//      音乐开关（SW3）关闭时，顶层已把左右声道数据置 0
//      （aud_left_out / aud_right_out），所以每列峰值都是 0 →
//      只画中心线 → 屏幕上就是一条绿色细直线 ✓
//      打开音乐后立刻变成跳动的波形，不需要任何额外开关。
//
//  【调节模式自动隐藏】
//      I_show 由顶层接 ~vcfg_adj_mode：运行模式显示波形；
//      进入调节模式（SW1 拨到 ON，调亮度/对比度/周期/缩放）时
//      波形自动隐藏，画面干净、方便观察调节效果（用户要求）。
//
//  【存储：分布式 RAM，不占块 RAM】
//      512 x 8bit 波形缓存 = 4Kb，用"变量地址异步读"写法
//      （wire wv = wave_ram[addr]），综合为 LUT RAM。
//      ★ 绝不能写成常量地址读（如 wave_ram[0]），否则会被摊成
//        触发器阵列，布局直接失败（工程里踩过这个坑）。
//      ★ 块 RAM 已用 56/64，这里一个块 RAM 都不占。
//
//  【流水线】
//      2 级输出寄存，RGB 与 hs/vs/de 统一延迟 2 拍，
//      下游（AXIS 转换）必须用本模块输出的 O_de/O_vs。
//==============================================================================
//  所属工程: 基于安路 EG4S20 的智能数字广告牌系统（赛题一 · 2026）
//==============================================================================

module audio_wave_osd (
    input  wire        video_clk,      // 视频时钟 25MHz
    input  wire        rst,            // 高有效复位

    // ---------------- 音频采样（已过 SW3 静音门控）----------------
    input  wire        I_valid,        // 48kHz 采样有效（单拍）
    input  wire [23:0] I_left,         // 左声道 24bit 有符号
    input  wire [23:0] I_right,        // 右声道 24bit 有符号

    // ---------------- 像素输入 ----------------
    input  wire        I_de,
    input  wire        I_hs,
    input  wire        I_vs,
    input  wire [23:0] I_rgb,

    // ---------------- 像素输出（比输入晚 2 拍）----------------
    output wire        O_de,
    output wire        O_hs,
    output wire        O_vs,
    output wire [23:0] O_rgb,

    // ---------------- 控制 ----------------
    // 1 = 显示波形；顶层接 ~vcfg_adj_mode：
    // 运行模式显示波形，进入调节模式（调亮度/对比度/周期/缩放）时自动隐藏，
    // 方便观察调节效果（用户 2026-10-31 要求）。
    input  wire        I_show
);

    //==========================================================================
    //  版面参数
    //==========================================================================
    localparam [9:0] WAVE_X0 = 10'd64;    // 波形区左边界（含）
    localparam [9:0] WAVE_X1 = 10'd576;   // 右边界（不含）→ 512 列
    localparam [9:0] WAVE_CY = 10'd418;   // 中心线 y
    localparam [23:0] COL_WAVE = 24'h00FF00;  // 纯绿

    // 每列对应的采样段长度：128 个 48kHz 采样 ≈ 2.67ms
    localparam [6:0] SEG_LEN = 7'd127;

    //==========================================================================
    //  第 1 部分：波形缓存与峰值检测
    //    wave_ram[0..511] : 每列的峰值幅度（8bit，取 16bit 峰值的高 8 位）
    //    wr_ptr           : 下一个写入位置（环形）
    //    每收满 128 个采样 → 写一列 → 指针前进
    //==========================================================================
    reg [7:0]  wave_ram [0:511];
    reg [8:0]  wr_ptr;       // 0~511（9 位，方便与列号相加回绕）
    reg [6:0]  seg_cnt;      // 段内采样计数
    reg [15:0] seg_peak;     // 段内峰值（16bit 幅度）

    // ---- 瞬时幅度：|L| 与 |R| 取较大者（取高 16 位，够用且省资源）----
    wire [15:0] amp_l = I_left[23]  ? (~I_left[23:8]  + 16'd1) : I_left[23:8];
    wire [15:0] amp_r = I_right[23] ? (~I_right[23:8] + 16'd1) : I_right[23:8];
    wire [15:0] amp   = (amp_l > amp_r) ? amp_l : amp_r;

    always @(posedge video_clk or posedge rst) begin
        if (rst) begin
            wr_ptr   <= 9'd0;
            seg_cnt  <= 7'd0;
            seg_peak <= 16'd0;
        end else if (I_valid) begin
            if (amp > seg_peak)
                seg_peak <= amp;
            if (seg_cnt >= SEG_LEN) begin
                seg_cnt  <= 7'd0;
                seg_peak <= 16'd0;
                // 本列峰值 = 段内峰值与当前采样取大（非阻塞下 seg_peak 还是旧值）
                wave_ram[wr_ptr[8:0]] <= (amp > seg_peak) ? amp[15:8] : seg_peak[15:8];
                wr_ptr   <= wr_ptr + 9'd1;
            end else begin
                seg_cnt <= seg_cnt + 7'd1;
            end
        end
    end

    //==========================================================================
    //  第 2 部分：像素坐标追踪（与 osd_adjust / marquee_osd 同一套写法）
    //==========================================================================
    reg [9:0] S_x;
    reg [9:0] S_y;
    reg       S_vs_d;

    wire S_vs_edge = (S_vs_d != I_vs);

    always @(posedge video_clk or posedge rst) begin
        if (rst) begin
            S_x    <= 10'd0;
            S_y    <= 10'd0;
            S_vs_d <= 1'b0;
        end else begin
            S_vs_d <= I_vs;
            if (S_vs_edge) begin
                S_x <= 10'd0;
                S_y <= 10'd0;
            end else if (I_de) begin
                if (S_x == 10'd639) begin
                    S_x <= 10'd0;
                    S_y <= S_y + 10'd1;
                end else begin
                    S_x <= S_x + 10'd1;
                end
            end
        end
    end

    //==========================================================================
    //  第 3 部分：波形取样与绘制判定
    //    第 col 列（0 = 最左 = 最旧）读取的地址 = wr_ptr + col（模 512）
    //      最右列 col=511 → wr_ptr+511 = wr_ptr-1 = 刚写入的最新值 ✓
    //    本列波形高度 dev = 峰值 >> 4（0~15 像素）
    //    判定：|y - 中心线| <= dev → 画绿色
    //==========================================================================
    wire [9:0] col10  = S_x - WAVE_X0;          // 0~511（仅 in_x 时有效）
    wire [8:0] raddr  = wr_ptr + col10[8:0];    // 模 512 环形回绕
    wire [7:0] wv     = wave_ram[raddr[8:0]];   // ★ 变量地址异步读 → LUT RAM

    wire [9:0] dev  = {6'b0, wv[7:4]};          // 0 ~ 15
    wire [9:0] ytop = WAVE_CY - dev;
    wire [9:0] ybot = WAVE_CY + dev;

    wire in_wave = (S_x >= WAVE_X0) && (S_x < WAVE_X1)
                && (S_y >= ytop) && (S_y <= ybot);

    //==========================================================================
    //  第 4 部分：2 级流水输出
    //==========================================================================
    reg [23:0] S_rgb_d1;
    reg [23:0] S_rgb_r;

    always @(posedge video_clk or posedge rst) begin
        if (rst) begin
            S_rgb_d1 <= 24'd0;
            S_rgb_r  <= 24'd0;
        end else begin
            // I_show = 0（调节模式）时直接透传原画面，波形完全隐藏
            S_rgb_d1 <= (I_show && in_wave) ? COL_WAVE : I_rgb;
            S_rgb_r  <= S_rgb_d1;
        end
    end

    assign O_rgb = S_rgb_r;

    // ★ 同步信号必须延迟与 RGB 相同的 2 拍
    video_sync_delay #(.STAGES(2)) u_sync_delay (
        .clk    (video_clk),
        .I_sync ({I_hs, I_vs, I_de}),
        .O_sync ({O_hs, O_vs, O_de})
    );

endmodule
