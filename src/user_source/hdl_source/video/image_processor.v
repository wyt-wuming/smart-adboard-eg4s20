//==============================================================================
//  文件名  : image_processor.v
//  模块名  : image_processor
//  功能    : 图像亮度 / 对比度实时调节（RGB 域逐像素流水线处理）
//------------------------------------------------------------------------------
//  【对应赛题】扩展要求 ④
//      "实时调节与信息叠加：利用板载开关或按键调节显示参数（如亮度、
//        对比度等），并尝试在画面上呈现参数变化信息。"
//
//  【算法】对 R / G / B 三个通道分别做同一条线性变换：
//
//      Y_out = clamp( ((Y - 128) * contrast) >> 4
//                     + (brightness - 16) * 8
//                     + 128 , 0, 255 )
//
//  逐项解释（零基础请看这里）：
//    (Y - 128)          : 把像素值搬到"以 0 为中心"的坐标系。128 是 8bit 灰度中点。
//    * contrast >> 4    : 对比度是 Q4 定点数（即数值除以 16 才是真实倍数）
//                         16 → 1.00 倍（中性，画面不变）
//                         0  → 0.00 倍（全部变成灰色）
//                         31 → 1.94 倍（黑白分明）
//                         对比度越大，(Y-128) 被"拉开"得越多。
//    (brightness-16)*8  : 亮度是整体平移。16 是中性（不增不减）。
//                         取值 0..31 → 偏移 -128 .. +120，步长 8。
//    + 128              : 搬回原来的坐标系（0..255）。
//    clamp(0,255)       : ★ 必须钳位！8bit 通道一旦回绕，画面会出现
//                          刺眼的彩色斑块（例如 250+20 变成 14 那种突变）。
//
//  【为什么直接在 RGB 上做，不转 YUV】
//  广告牌是静态图片展示，RGB 域调节的观感完全够用；而且省掉 YUV 转换的
//  乘加运算和额外的行缓存。对零基础队伍来说，"看得懂 + 不出错"比"理论最优"重要。
//
//  【流水线级数】共 2 级（第 1 级做乘加与钳位，第 2 级寄存输出）
//      → hs/vs/de 必须延迟 2 拍，由 video_sync_delay #(.STAGES(2)) 完成
//      ★ 若以后改动级数，必须同步改下面的 STAGES，否则画面左右偏移！
//
//  【上板自检技巧 —— 阶段 1a 的回归测试】
//  把 brightness=16、contrast=16 代入公式：
//      (Y-128)*16>>4 = (Y-128)   →   +0   →   +128   =   Y
//  即输出严格等于输入。所以：
//      · 上板后画面与"不加本模块"时逐像素一致 → 位序、延迟全部正确 ✔
//      · 画面整体右移几像素          → video_sync_delay 级数写错
//      · 出现彩色斑块/惨白            → 有符号运算或钳位写错
//------------------------------------------------------------------------------
//  所属工程: 基于安路 EG4S20 的智能数字广告牌系统（赛题一改造）
//  说明    : 详细中文注释版，供零基础队员阅读理解
//==============================================================================

module image_processor (
    input  wire        video_clk,      // 视频时钟 video_clk (25MHz)
    input  wire        rst,            // 高有效复位（工程里是 rst_all）

    // ---------------- 像素输入 ----------------
    input  wire        I_de,           // 数据有效 Data Enable（=1 时才是有效像素）
    input  wire        I_hs,           // 行同步
    input  wire        I_vs,           // 场同步
    input  wire [23:0] I_rgb,          // 24bit RGB = {R[7:0], G[7:0], B[7:0]}

    // ---------------- 像素输出（比输入晚 2 拍）----------------
    output wire        O_de,
    output wire        O_hs,
    output wire        O_vs,
    output wire [23:0] O_rgb,

    // ---------------- 调节参数（来自按键状态机，已锁存到本时钟域）----------------
    input  wire [4:0]  I_brightness,   // 亮度 0..31，16 = 中性
    input  wire [4:0]  I_contrast      // 对比度 0..31，16 = 中性（Q4 定点）
);

    //==========================================================================
    //  单通道处理函数
    //
    //  ★ 这里必须使用"有符号"运算。零基础最容易踩的坑是用无符号减法：
    //    那样 (Y - 128) 在 Y < 128 时会回绕成一个巨大的正数，
    //    经过后面的运算后全被钳到 255，画面一片惨白。
    //    所以下面所有中间变量都声明为 signed，并用 $signed() 显式转换。
    //==========================================================================
    function [7:0] proc_ch;
        input [7:0] y;                 // 输入通道值 0..255
        input [4:0] bri;               // 亮度参数 0..31
        input [4:0] con;               // 对比度参数 0..31
        reg signed [15:0] c;           // 中间量：中心化并乘过对比度后的值
        reg signed [15:0] s;           // 中间量：最终结果
        begin
            // ---- 第 1 步：中心化 (Y - 128)，取值范围 -128 .. +127 ----
            c = $signed({1'b0, y}) - 16'sd128;

            // ---- 第 2 步：乘对比度系数，再算术右移 4 位 ----
            //      ">>>" 是算术右移（保留符号位），不是逻辑右移 ">>"。
            //      con = 16 时，等价于 乘 1.0。
            c = (c * $signed({1'b0, con})) >>> 4;

            // ---- 第 3 步：加亮度偏移，并搬回 0..255 坐标系 ----
            //      "<<< 3" 即乘 8；bri = 16 时偏移量为 0。
            s = c + (($signed({1'b0, bri}) - 16'sd16) <<< 3) + 16'sd128;

            // ---- 第 4 步：钳位到 0..255（★ 绝不能省）----
            if (s[15] == 1'b1)         // 最高位为 1 → 负数 → 下钳到 0
                proc_ch = 8'd0;
            else if (s > 16'sd255)     // 超过 255 → 上钳到 255
                proc_ch = 8'd255;
            else
                proc_ch = s[7:0];      // 正常范围，取低 8 位
        end
    endfunction

    //==========================================================================
    //  第 1 级流水：R/G/B 三通道并行运算并寄存
    //  三个通道共用同一个 proc_ch 函数，综合工具会自动复制成 3 份硬件电路
    //==========================================================================
    reg [23:0] S_rgb_d1;
    always @(posedge video_clk or posedge rst) begin
        if (rst)
            S_rgb_d1 <= 24'd0;
        else begin
            S_rgb_d1[23:16] <= proc_ch(I_rgb[23:16], I_brightness, I_contrast);  // R 通道
            S_rgb_d1[15:8]  <= proc_ch(I_rgb[15:8],  I_brightness, I_contrast);  // G 通道
            S_rgb_d1[7:0]   <= proc_ch(I_rgb[7:0],   I_brightness, I_contrast);  // B 通道
        end
    end

    //==========================================================================
    //  第 2 级流水：再打一拍输出
    //  为什么打两拍？让"乘法"和"钳位加法"分处不同时钟级，缩短关键路径。
    //  25MHz 其实非常宽裕，但保持这个习惯有利于后期继续往流水线里加模块。
    //==========================================================================
    reg [23:0] S_rgb_d2;
    always @(posedge video_clk or posedge rst) begin
        if (rst)
            S_rgb_d2 <= 24'd0;
        else
            S_rgb_d2 <= S_rgb_d1;
    end

    assign O_rgb = S_rgb_d2;

    //==========================================================================
    //  ★ 同步信号延迟级数必须与上面 RGB 的 2 级流水严格一致
    //     改这里之前请先数清楚 RGB 被打了几拍！
    //==========================================================================
    video_sync_delay #(
        .STAGES (2)
    ) u_sync_delay (
        .clk    (video_clk),
        .I_sync ({I_hs, I_vs, I_de}),      // 拼接：{hs, vs, de}
        .O_sync ({O_hs, O_vs, O_de})       // 解拼：顺序一一对应
    );

endmodule
