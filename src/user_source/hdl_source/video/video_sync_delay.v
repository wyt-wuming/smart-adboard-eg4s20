//==============================================================================
//  文件名  : video_sync_delay.v
//  模块名  : video_sync_delay
//  功能    : 视频同步信号 (hs / vs / de) 的参数化延迟线
//  时钟域  : 跟随调用方时钟（纯延迟，参数化）
//------------------------------------------------------------------------------
//  【为什么需要这个模块 —— 改造工程最容易踩的坑之一】
//
//  本工程的像素数据 (vout_data) 是"逐拍流水"的：数据每经过一级图像处理，
//  就被时钟打一拍（寄存一次）。而行同步 hs / 场同步 vs / 数据有效 de
//  是告诉显示器"当前这个像素在屏幕的哪个位置"的信号。
//
//  如果 hs/vs/de 不跟着像素数据打同样多的拍数，两者就会错位：
//    · 轻则画面整体左右偏移若干像素
//    · 重则下游 video_rgb_to_axis_640x480 靠 de/vs 推导 SOF/EOF 和 x 坐标
//      会判错帧边界，导致画面撕裂、滚动、花屏
//
//  所以铁律：**每插入一级图像处理，就必须把 hs/vs/de 延迟相同的拍数。**
//  本模块把这个"延迟几拍"参数化，避免每个图像处理模块各写一段移位寄存器
//  ——一旦各处级数不一致，偏移 bug 极难定位。
//
//  【用法举例】某个模块内部把 RGB 打了两拍，那么：
//      video_sync_delay #(.STAGES(2)) u_sync_delay (
//          .clk    (video_clk),
//          .I_sync ({I_hs, I_vs, I_de}),    // 注意拼接顺序：{hs, vs, de}
//          .O_sync ({O_hs, O_vs, O_de})     // 解拼顺序要对应
//      );
//  参数 STAGES 必须严格等于同模块内 RGB 数据被打的拍数。
//------------------------------------------------------------------------------
//  所属工程: 基于安路 EG4S20 的智能数字广告牌系统（赛题一改造）
//  说明    : 详细中文注释版，供零基础队员阅读理解
//==============================================================================

module video_sync_delay #(
    parameter integer STAGES = 1,      // 延迟拍数（必须 >= 1），等于同模块 RGB 的流水级数
    parameter integer WIDTH  = 3       // 同步信号位宽，默认 3 位 = {hs, vs, de}
)(
    input  wire              clk,      // 视频时钟 video_clk (25MHz)
    input  wire [WIDTH-1:0]  I_sync,   // 输入同步信号组
    output wire [WIDTH-1:0]  O_sync    // 输出同步信号组，比输入晚 STAGES 拍
);

    //--------------------------------------------------------------------------
    // 移位寄存器组
    //   S_dly[0]         : 最新采入的一拍
    //   S_dly[STAGES-1]  : 最"老"的一拍，也就是延迟了 STAGES 拍的输出
    //
    // 说明：这里刻意不加复位。因为 hs/vs/de 是"随帧流动"的连续信号，
    //       上电瞬间的初值最多影响第一帧画面（显示器还没来得及锁定），
    //       不加复位可以省下复位网络的布线资源。这与工程中
    //       video_delay.v 对 hs/vs/de 的处理方式保持一致。
    //--------------------------------------------------------------------------
    reg [WIDTH-1:0] S_dly [0:STAGES-1];

    integer i;
    always @(posedge clk) begin
        S_dly[0] <= I_sync;                       // 第 1 级：直接采输入
        for (i = 1; i < STAGES; i = i + 1)
            S_dly[i] <= S_dly[i-1];               // 后续各级：逐级向后移动
    end

    assign O_sync = S_dly[STAGES-1];              // 输出最老的一级

endmodule
