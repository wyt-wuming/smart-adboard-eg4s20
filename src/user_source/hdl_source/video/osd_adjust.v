//==============================================================================
//  文件名  : osd_adjust.v
//  模块名  : osd_adjust
//  功能    : 调节模式下的 OSD 界面 —— 屏幕左上角显示绿色汉字 + 数值
//------------------------------------------------------------------------------
//  【显示效果】只有进入"调节模式"（拨码 SW1 = ON）时才显示，平时完全透明。
//
//      显示在左上角，8 个 16x16 字符，纯绿色（RGB = 00FF00）：
//
//        ┌──────────────────────┐
//        │ 亮度   16            │   ← 调亮度时
//        │ 对比度 24            │   ← 调对比度时
//        │ 周期   05秒          │   ← 调周期时
//        └──────────────────────┘
//
//      背景完全透明（不点亮的地方直接透出原来的广告画面），
//      不做半透明底框、不做图形 —— 就是"绿色文字直接浮在画面上"。
//
//  【版面坐标】
//      文字区左上角起点：(x=8, y=8)
//      每个字符 16x16 像素，一行 8 个字符 → 占 x:8~135, y:8~23
//
//  【字符排布（8 列）】
//      列0 列1 列2  列3   列4  列5  列6   列7
//      ┌───┬───┬───┬───┬───┬───┬───┬───┐
//      │ 参数名（最多3字）│空格│ 十位│ 个位│单位│空格│
//      └───┴───┴───┴───┴───┴───┴───┴───┘
//        亮度  → [亮][度][空]
//        对比度→ [对][比][度]
//        周期  → [周][期][空]       单位显示"秒"
//
//  【和图像流水线的关系】
//      本模块插在"亮度/对比度处理"之后、"转 RGB/AXIS"之前：
//        vout_base → [image_processor] → [osd_adjust] → axis → HDMI
//      ★ 内部把 RGB 和 hs/vs/de 都延迟 2 拍（ROM 读 1 拍 + 输出寄存 1 拍），
//        所以下游必须用本模块输出的 O_de/O_hs/O_vs，不能再用原始的。
//------------------------------------------------------------------------------
//  所属工程: 基于安路 EG4S20 的智能数字广告牌系统（赛题一改造）
//==============================================================================

module osd_adjust (
    input  wire        video_clk,      // 视频时钟 25MHz
    input  wire        rst,            // 高有效复位

    // ---------------- 像素输入 ----------------
    input  wire        I_de,
    input  wire        I_hs,
    input  wire        I_vs,
    input  wire [23:0] I_rgb,

    // ---------------- 像素输出（比输入晚 2 拍）----------------
    output wire        O_de,
    output wire        O_hs,
    output wire        O_vs,
    output wire [23:0] O_rgb,

    // ---------------- 显示控制（来自拨码开关，已在 video_clk 域）----------------
    input  wire        I_show,         // 1 = 显示 OSD（调节模式）  0 = 完全透明
    input  wire [1:0]  I_sel,          // 当前调节项 0=亮度 1=对比度 2=周期
    input  wire [15:0] I_value         // 要显示的数值（0~31）
);

    //==========================================================================
    //  第 1 部分：像素坐标追踪
    //    显示是 640x480，de 有效时逐像素输出。
    //    用 x/y 计数器记录"当前像素在屏幕上的位置"，
    //    这样才能判断"这个像素是不是落在文字区里"。
    //==========================================================================
    reg [9:0] S_x;          // 当前像素 x（0~639）
    reg [9:0] S_y;          // 当前像素 y（0~479）
    reg       S_vs_d;

    wire S_vs_edge = (S_vs_d != I_vs);      // vs 跳变 = 一帧的边界

    always @(posedge video_clk or posedge rst) begin
        if (rst) begin
            S_x    <= 10'd0;
            S_y    <= 10'd0;
            S_vs_d <= 1'b0;
        end else begin
            S_vs_d <= I_vs;
            if (S_vs_edge) begin
                // 帧边界：坐标归零
                S_x <= 10'd0;
                S_y <= 10'd0;
            end else if (I_de) begin
                if (S_x == 10'd639) begin
                    S_x <= 10'd0;
                    S_y <= S_y + 10'd1;     // 换行
                end else begin
                    S_x <= S_x + 10'd1;
                end
            end
        end
    end

    //==========================================================================
    //  第 2 部分：文字区判定 与 字符索引计算
    //    文字区：x = 8 ~ 135（8 个字符），y = 8 ~ 23（16 行）
    //==========================================================================
    localparam [9:0] X0 = 10'd8;
    localparam [9:0] Y0 = 10'd8;
    localparam [9:0] X1 = 10'd136;      // 8+8*16
    localparam [9:0] Y1 = 10'd24;       // 8+16

    wire in_text = (S_x >= X0) && (S_x < X1) && (S_y >= Y0) && (S_y < Y1);

    // 当前像素落在第几个字符（列 0~7）和字符内的第几行（0~15）
    wire [3:0] col_now = (S_x - X0) >> 4;
    wire [3:0] row_now = (S_y - Y0);

    //--------------------------------------------------------------------------
    // 数值拆成十位 / 个位（数值范围 0~31，两位就够）
    //--------------------------------------------------------------------------
    wire [15:0] val_div10 = I_value / 16'd10;
    wire [3:0]  d_tens    = val_div10[3:0];
    wire [3:0]  d_ones    = (I_value % 16'd10);

    //--------------------------------------------------------------------------
    // 第 col 列显示哪个字符（字库索引）
    //   0~9  = 数字 '0'~'9'
    //   10=亮 11=度 12=对 13=比 14=周 15=期 16=秒
    //   17   = 空白
    //--------------------------------------------------------------------------
    reg [4:0] ch_now;
    always @(*) begin
        case (col_now)
            // ---- 参数名 ----
            4'd0: ch_now = (I_sel == 2'd0) ? 5'd10 :      // 亮
                           (I_sel == 2'd1) ? 5'd12 :      // 对
                                             5'd14;       // 周
            4'd1: ch_now = (I_sel == 2'd0) ? 5'd11 :      // 度
                           (I_sel == 2'd1) ? 5'd13 :      // 比
                                             5'd15;       // 期
            4'd2: ch_now = (I_sel == 2'd1) ? 5'd11 : 5'd17;  // 对比度→"度"，其余空格
            // ---- 空格 ----
            4'd3: ch_now = 5'd17;
            // ---- 数值（两位）----
            4'd4: ch_now = {1'b0, d_tens};
            4'd5: ch_now = {1'b0, d_ones};
            // ---- 单位：周期显示"秒"，其余空格 ----
            4'd6: ch_now = (I_sel == 2'd2) ? 5'd16 : 5'd17;
            // ---- 末位空格 ----
            default: ch_now = 5'd17;
        endcase
    end

    //==========================================================================
    //  第 3 部分：字库 ROM
    //    地址 = {字符索引[4:0], 行号[3:0]}，读出该行的 16 个像素
    //    ROM 有 1 拍读延迟，所以下面的判定要用"延迟 1 拍的坐标"
    //==========================================================================
    wire [8:0]  rom_addr = {ch_now, row_now};
    wire [15:0] rom_data;

    font_rom u_font_rom (
        .clk  (video_clk),
        .addr (rom_addr),
        .data (rom_data)
    );

    //==========================================================================
    //  第 4 部分：输出（把绿色文字叠加到画面上）
    //    延迟对齐：
    //      第 1 级 —— 坐标和 RGB 各打一拍（与 ROM 的读延迟对齐）
    //      第 2 级 —— 混色结果再打一拍输出
    //    总共 2 拍
    //==========================================================================
    reg [9:0]  S_x_d, S_y_d;
    reg [23:0] S_rgb_d1;

    always @(posedge video_clk or posedge rst) begin
        if (rst) begin
            S_x_d    <= 10'd0;
            S_y_d    <= 10'd0;
            S_rgb_d1 <= 24'd0;
        end else begin
            S_x_d    <= S_x;
            S_y_d    <= S_y;
            S_rgb_d1 <= I_rgb;
        end
    end

    // 延迟后的"是否在文字区内"判定（与 rom_data 同拍）
    wire in_text_d = I_show &&
                     (S_x_d >= X0) && (S_x_d < X1) &&
                     (S_y_d >= Y0) && (S_y_d < Y1);

    // 字符内横向第几个像素（0~15），最左边是 bit15
    wire [3:0] px_in_char = (S_x_d - X0) & 4'hF;
    wire       font_on    = rom_data[4'd15 - px_in_char];   // 1 = 该像素点亮

    reg [23:0] S_rgb_r;
    always @(posedge video_clk or posedge rst) begin
        if (rst)
            S_rgb_r <= 24'd0;
        else if (in_text_d && font_on)
            S_rgb_r <= 24'h00FF00;     // ★ 纯绿色文字
        else
            S_rgb_r <= S_rgb_d1;       // ★ 其余像素：透出原画面（背景完全透明）
    end

    assign O_rgb = S_rgb_r;

    // ★ 同步信号必须延迟与 RGB 相同的 2 拍
    video_sync_delay #(.STAGES(2)) u_sync_delay (
        .clk    (video_clk),
        .I_sync ({I_hs, I_vs, I_de}),
        .O_sync ({O_hs, O_vs, O_de})
    );

endmodule
